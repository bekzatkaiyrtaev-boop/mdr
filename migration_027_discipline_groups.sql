-- ============================================================
-- Миграция 027 — заголовки-группы в "Проект" → "Разделы и исполнители".
--
-- Позволяет сгруппировать разделы под сворачиваемым заголовком, например
-- "Электрическая часть" со всеми электротехническими разделами внутри.
-- Заголовок — обычная строка в public.disciplines (is_header=true), без
-- кода и исполнителей; обычные разделы ссылаются на свой заголовок через
-- group_id (необязательно — раздел может быть и без группы).
--
-- Выполнить в Supabase → SQL Editor на уже созданном проекте
-- ============================================================

alter table public.disciplines
  add column if not exists is_header boolean not null default false,
  add column if not exists group_id uuid references public.disciplines(id) on delete set null;
